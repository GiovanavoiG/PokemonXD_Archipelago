"""Writes `game_data/battle_index.py`: which trainer each battle index fights.

The AP patch logs a won battle as the u16 the game keeps at 0x804EB910 -- an index into `common_rel`'s Battles
table (pointer-table entry 26, 442 entries of 0x3C bytes). Each entry holds four player slots from +0x1C, 8 bytes
apiece: {deck id u16, trainer index u16, controller u32}. Slot 0 is always the hero (deck 0, trainer 5000); every
story and Mt. Battle fight has exactly one opponent, in slot 1. Deck 1 is `DeckData_Story` (trainer indices 2-232,
the `trainer_roster.TRAINERS` rows) and deck 2 is `DeckData_Hundred` (Mt. Battle, 1-100). The other decks are the
tutorial, colosseum and Battle CD fights, which hold no checks and are left out.

    python3 -m pokemon_xd.tools.extract_battle_index <common_rel.rel> <out.py>
"""
from __future__ import annotations

import struct
import sys

try:
    from .xd_rel_format import RelFile
except ImportError:            # run as a plain script
    from xd_rel_format import RelFile

BATTLES_POINTER = 26
BATTLE_ENTRY_SIZE = 0x3C
BATTLE_PLAYERS_OFFSET = 0x1C
BATTLE_PLAYER_SIZE = 8
STORY_DECK = 1
MT_BATTLE_DECK = 2


def extract(rel_bytes: bytes) -> "dict[int, tuple[int, int]]":
    rel = RelFile(rel_bytes, is_common=True, label="common_rel")
    base = rel.entry_address(BATTLES_POINTER)
    count = rel.entry_value(BATTLES_POINTER + 1)
    out: "dict[int, tuple[int, int]]" = {}
    for index in range(count):
        entry = rel_bytes[base + index * BATTLE_ENTRY_SIZE:base + (index + 1) * BATTLE_ENTRY_SIZE]
        deck, trainer, _controller = struct.unpack_from(">HHI", entry, BATTLE_PLAYERS_OFFSET + BATTLE_PLAYER_SIZE)
        if deck in (STORY_DECK, MT_BATTLE_DECK):
            out[index] = (deck, trainer)
    return out


def render(table: "dict[int, tuple[int, int]]") -> str:
    lines = [
        '"""GENERATED by `tools/extract_battle_index.py` from `common_rel`\'s Battles table -- do not edit.',
        "",
        "{battle index: (deck id, trainer index)} for every battle whose opponent is a story (deck 1, the",
        "`trainer_roster.TRAINERS` index) or Mt. Battle (deck 2, 1-100) trainer. The AP patch logs won battles by",
        'battle index; this is how the client turns one into a trainer."""',
        "from __future__ import annotations",
        "",
        f"STORY_DECK = {STORY_DECK}",
        f"MT_BATTLE_DECK = {MT_BATTLE_DECK}",
        "",
        'BATTLE_OPPONENTS: "dict[int, tuple[int, int]]" = {',
    ]
    lines += [f"    {index}: ({deck}, {trainer})," for index, (deck, trainer) in sorted(table.items())]
    lines += ["}", ""]
    return "\n".join(lines)


def main(argv: "list[str]") -> int:
    with open(argv[1], "rb") as handle:
        table = extract(handle.read())
    # The first story battle is Miror B.'s (trainer 2) and the last Mt. Battle one is Battlus (trainer 100).
    assert (STORY_DECK, 2) in table.values(), "not the Battles table: no fight against story trainer 2"
    assert table.get(215) == (MT_BATTLE_DECK, 100), "not the Battles table: battle 215 is not Mt. Battle's 100th"
    with open(argv[2], "w", newline="\n") as handle:
        handle.write(render(table))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
