def national_dex_for(internal_index: int) -> int | None:
    """Resolve one raw species/Pokemon-index value (as found in DTNR/DPKM/PokeSpot data) to its real
    National Dex number. Returns None for a reserved/unused slot or an out-of-range index."""
    rec = INTERNAL_INDEX_TO_NATIONAL_DEX.get(internal_index)
    if rec is None or rec[1] is None:
        return None
    return rec[0]


def name_for(internal_index: int) -> str | None:
    """Resolve a raw species/Pokemon-index value to this game's own display name, which is correct regardless
    of National Dex ordering. Returns None for a reserved/unused slot or an out-of-range index."""
    rec = INTERNAL_INDEX_TO_NATIONAL_DEX.get(internal_index)
    if rec is None:
        return None
    return rec[1]


# Reverse of national_dex_for(), for callers that need to WRITE a species into a raw record. Built from the
# table above, so it stays in sync; injective by construction, so a plain dict is safe.
NATIONAL_DEX_TO_INTERNAL_INDEX: dict[int, int] = {
    national_dex: internal_index
    for internal_index, (national_dex, name) in INTERNAL_INDEX_TO_NATIONAL_DEX.items()
    if name is not None
}


def internal_index_for_national_dex(national_dex: int) -> int | None:
    """Resolve a real National Dex number to the internal index that must be written into a raw
    DTNR/DPKM/PokeSpot species field. Returns None if this table has no entry (species.py's range is 1-386;
    this table additionally covers 387/388, Bonsly and Munchlax)."""
    return NATIONAL_DEX_TO_INTERNAL_INDEX.get(national_dex)


# LIVE RAM species index, confirmed 2026-09-06 against the player's running game (PARTY_BASE bridge dump,
# each slot cross-checked against its own live nickname).
#
# ram_client.PARTY_SPECIES_OFFSET uses a COMPACTED form of this table's ordering: the 25 reserved slots
# 252-276 are squeezed out, so Generation III starts at raw 252, not 277. Confirmed on four un-nicknamed
# slots -- raw 330 MAWILE -> 355 -> dex 303; raw 367 RALTS -> 392 -> 280; raw 310 MAKUHITA -> 335 -> 296;
# raw 273 SEEDOT -> 298 -> 273 (that last prints its own raw value back by coincidence) -- and it explains
# read_party_species's old "unreliable field" caveat: raw 316 on a SPHEAL looked like GULPIN (dex 316), but
# 316+25=341 and national_dex_for(341)==363. The field was never desynced, just uncompacted.
#
# Whether BOX_SLOT_SPECIES_OFFSET and PARTY_RECAP_SPECIES_OFFSET share it is unconfirmed, but both call
# sites are closed: read_box_slot_species converts and drops what it cannot resolve (109 raw values in
# 276-386 differ under the conversion and each names a real `Catch - ` location, so an unconverted read
# could credit an unearned check), and read_party_recap_species never reads the field numerically.

LIVE_INDEX_GAP_SIZE = 25  # number of reserved/unused master-table slots (252-276) that live RAM's index skips
LIVE_INDEX_GAP_START = 252  # first live raw value that needs the +LIVE_INDEX_GAP_SIZE adjustment


def national_dex_for_live_species(live_species_id: int | None) -> int | None:
    """Resolve a raw species value read from LIVE RAM (e.g. ram_client.PARTY_SPECIES_OFFSET) to its National
    Dex number -- see the comment above for the compaction. Returns None for 0/None or an unresolvable value."""
    if not live_species_id:
        return None
    if live_species_id < LIVE_INDEX_GAP_START:
        return live_species_id
    return national_dex_for(live_species_id + LIVE_INDEX_GAP_SIZE)


def name_for_live_species(live_species_id: int | None) -> str | None:
    """Same live-RAM-index adjustment as national_dex_for_live_species(), but returns this game's own display
    name instead of the National Dex number. Returns None for 0/None (empty slot) or an unresolvable value."""
    if not live_species_id:
        return None
    if live_species_id < LIVE_INDEX_GAP_START:
        return name_for(live_species_id)
    return name_for(live_species_id + LIVE_INDEX_GAP_SIZE)
